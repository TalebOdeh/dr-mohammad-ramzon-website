  function loadMedia() {
    if (mediaLoaded) {
      renderCases();
      renderVideos();
      return;
    }
    var caseChecks = CASES.map(function (item) {
      return Promise.all([imageOk(item.before), imageOk(item.after)]).then(function (flags) {
        return flags[0] && flags[1] ? item : null;
      });
    });
    var videoChecks = VIDEOS.map(function (item) {
      return Promise.all([fileOk(item.src), imageOk(item.poster)]).then(function (flags) {
        if (!flags[0]) return null;
        return { id: item.id, src: item.src, poster: item.poster, posterOk: flags[1] };
      });
    });
    Promise.all([Promise.all(caseChecks), Promise.all(videoChecks)]).then(function (result) {
      readyCases = result[0].filter(Boolean);
      readyVideos = result[1].filter(Boolean);
      mediaLoaded = true;
      renderCases();
      renderVideos();
    });
  }

