  function initResults() {
    var root = document.getElementById("results");
    var track = document.getElementById("results-track");
    var prev = document.getElementById("results-prev");
    var next = document.getElementById("results-next");
    if (!root || !track || !prev || !next) return;

    var reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

    function slides() {
      return Array.prototype.filter.call(track.children, function (slide) {
        return slide.tagName === "FIGURE" && slide.isConnected && !slide.hidden;
      });
    }

    function nearest() {
      var list = slides();
      var mid = track.getBoundingClientRect().left + track.clientWidth / 2;
      var best = 0;
      var bestDist = Infinity;
      list.forEach(function (slide, i) {
        var rect = slide.getBoundingClientRect();
        var dist = Math.abs(rect.left + rect.width / 2 - mid);
        if (dist < bestDist) {
          bestDist = dist;
          best = i;
        }
      });
      return best;
    }

    function sync() {
      var list = slides();
      if (!list.length) {
        root.hidden = true;
        return;
      }
      var index = nearest();
      prev.disabled = index <= 0;
      next.disabled = index >= list.length - 1;
    }

    function go(to) {
      var list = slides();
      if (!list.length) return;
      var index = Math.max(0, Math.min(list.length - 1, to));
      var delta = list[index].getBoundingClientRect().left - track.getBoundingClientRect().left;
      track.scrollBy({ left: delta, behavior: reduce ? "auto" : "smooth" });
      prev.disabled = index <= 0;
      next.disabled = index >= list.length - 1;
    }

    track.querySelectorAll("img").forEach(function (img) {
      img.addEventListener("error", function () {
        var frame = img.closest("figure");
        if (frame) frame.remove();
        if (!slides().length) root.hidden = true;
        else sync();
      });
    });

    prev.addEventListener("click", function () { go(nearest() - 1); });
    next.addEventListener("click", function () { go(nearest() + 1); });

    track.addEventListener("keydown", function (event) {
      if (event.key !== "ArrowLeft" && event.key !== "ArrowRight") return;
      event.preventDefault();
      var forward = event.key === "ArrowRight";
      if (document.documentElement.dir === "rtl") forward = !forward;
      go(nearest() + (forward ? 1 : -1));
    });

    var scrollTimer = 0;
    track.addEventListener("scroll", function () {
      window.clearTimeout(scrollTimer);
      scrollTimer = window.setTimeout(sync, 80);
    }, { passive: true });

    sync();
  }

